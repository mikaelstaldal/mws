#!/usr/bin/env python3
"""Generates GeneratedProviderFloors.kt from the PASS rows in provider-compatibility.md.

Run after adding or changing a matrix row, or after changing the pinned AndroidX WebKit
version, and commit the result. With --check, fails instead if the committed file is stale.
"""
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MATRIX = ROOT / "provider-compatibility.md"
VERSIONS = ROOT / "gradle" / "libs.versions.toml"
OUTPUT = ROOT / "app/src/main/java/nu/staldal/mws/GeneratedProviderFloors.kt"


def fail(message):
    sys.exit(f"{MATRIX.name}: {message}")


def floors(matrix, webkit):
    if "| Provider package | Exact provider version |" not in matrix:
        fail("Provider compatibility matrix missing")
    result = {}
    rows = [line for line in matrix.splitlines() if line.startswith("| ")][2:]
    for row in rows:
        cells = [cell.strip() for cell in row.strip().strip("|").split("|")]
        if len(cells) != 9:
            fail(f"Malformed provider compatibility row: {row}")
        outcome = cells[8].removeprefix("`").removesuffix("`")
        if outcome not in ("PASS", "FAIL", "BLOCKED"):
            fail(f"Invalid provider compatibility result: {cells[8]}")
        if outcome != "PASS":
            continue
        package, version = cells[0], cells[1]
        if not re.fullmatch(r"[a-zA-Z][a-zA-Z0-9_.]*", package):
            fail(f"Invalid provider package: {package}")
        if cells[4] != webkit:
            fail(f"Qualified provider uses different WebKit version: {package}")
        if any(not cell or cell == "—" for cell in cells[2:8]):
            fail(f"Qualified provider lacks evidence: {package}")
        if not re.fullmatch(r"[0-9]+(\.[0-9]+)*", version):
            fail(f"Invalid provider version: {version}")
        parts = [int(part) for part in version.split(".")]
        if package not in result or padded(parts, result[package]) < padded(result[package], parts):
            result[package] = parts
    if not result:
        fail("Release requires at least one qualifying PASS provider")
    return dict(sorted(result.items()))


def padded(left, right):
    """Compares versions with missing components as zero."""
    return left + [0] * (len(right) - len(left))


def source(values):
    entries = ",\n".join(
        f'        "{package}" to listOf({", ".join(map(str, parts))})'
        for package, parts in values.items()
    )
    return f"""package nu.staldal.mws

/** Generated by scripts/generate-provider-floors.py from the PASS rows in provider-compatibility.md. */
internal object GeneratedProviderFloors {{
    val values: Map<String, List<Int>> = mapOf(
{entries}
    )
}}
"""


def main():
    webkit = tomllib.loads(VERSIONS.read_text())["versions"]["webkit"]
    generated = source(floors(MATRIX.read_text(), webkit))
    if sys.argv[1:] == ["--check"]:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            sys.exit(f"{OUTPUT.relative_to(ROOT)} is stale; run scripts/generate-provider-floors.py")
    elif sys.argv[1:]:
        sys.exit("usage: generate-provider-floors.py [--check]")
    else:
        OUTPUT.write_text(generated)


if __name__ == "__main__":
    main()
